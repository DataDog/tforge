package generate

import (
	"github.com/dave/jennifer/jen"

	"tforge/schema"
)

// ProviderGenerator handles generation of provider configuration code.
type ProviderGenerator struct {
	config Config
	file   *jen.File
}

// NewProviderGenerator creates a new provider generator.
func NewProviderGenerator(cfg Config) *ProviderGenerator {
	return &ProviderGenerator{
		config: cfg,
		file:   jen.NewFile(cfg.PackageName),
	}
}

// GenerateProvider generates code for provider configuration.
func (pg *ProviderGenerator) GenerateProvider(ps *schema.ProviderSchema, providerName string) error {
	pg.file.HeaderComment("Code generated by tforge. DO NOT EDIT.")

	block := ps.ProviderBlock()

	// Generate main provider config struct
	pg.generateProviderStruct(block, providerName)

	// Generate nested types
	if block != nil {
		pg.generateNestedTypes(block, "ProviderConfig")
	}

	// Generate helper functions
	pg.generateProviderHelpers(providerName)

	return nil
}

// generateProviderStruct generates the provider configuration struct.
func (pg *ProviderGenerator) generateProviderStruct(block *schema.Block, providerName string) {
	pg.file.Commentf("ProviderConfig represents the %s provider configuration.", providerName)
	pg.file.Type().Id("ProviderConfig").StructFunc(func(s *jen.Group) {
		if block == nil {
			return
		}

		for _, attr := range block.Attributes() {
			pg.generateAttributeField(s, attr)
		}

		for _, nb := range block.NestedBlocks() {
			pg.generateNestedBlockField(s, nb)
		}
	})
	pg.file.Line()
}

// generateAttributeField generates a struct field for an attribute.
func (pg *ProviderGenerator) generateAttributeField(s *jen.Group, attr *schema.Attribute) {
	fieldName := toGoName(attr.Name())
	goType := schema.GoTypeName(attr.Type())
	jsonTag := attr.Name()

	if (attr.Optional() || attr.Computed()) && pg.config.OmitEmpty {
		jsonTag += ",omitempty"
	}

	field := s.Id(fieldName)
	field = field.Add(jenTypeFromString(goType))
	field.Tag(map[string]string{"json": jsonTag})
}

// generateNestedBlockField generates a field for a nested block.
func (pg *ProviderGenerator) generateNestedBlockField(s *jen.Group, nb *schema.NestedBlock) {
	fieldName := toGoName(nb.Name())
	typeName := fieldName + "Block"
	jsonTag := nb.Name() + ",omitempty"

	field := s.Id(fieldName)

	switch nb.NestingMode() {
	case "single", "group":
		field.Op("*").Id(typeName)
	case "list", "set":
		field.Index().Op("*").Id(typeName)
	case "map":
		field.Map(jen.String()).Op("*").Id(typeName)
	default:
		field.Op("*").Id(typeName)
	}

	field.Tag(map[string]string{"json": jsonTag})
}

// generateNestedTypes generates struct types for nested blocks.
func (pg *ProviderGenerator) generateNestedTypes(block *schema.Block, parentName string) {
	for _, nb := range block.NestedBlocks() {
		typeName := toGoName(nb.Name()) + "Block"

		pg.file.Commentf("%s represents a %s block in %s.", typeName, nb.Name(), parentName)
		pg.file.Type().Id(typeName).StructFunc(func(s *jen.Group) {
			innerBlock := nb.Block()
			if innerBlock == nil {
				return
			}

			for _, attr := range innerBlock.Attributes() {
				pg.generateAttributeField(s, attr)
			}

			for _, innerNB := range innerBlock.NestedBlocks() {
				pg.generateNestedBlockField(s, innerNB)
			}
		})
		pg.file.Line()

		// Recursively generate nested types
		if nb.Block() != nil {
			pg.generateNestedTypes(nb.Block(), typeName)
		}
	}
}

// generateProviderHelpers generates helper functions for the provider.
func (pg *ProviderGenerator) generateProviderHelpers(providerName string) {
	// ProviderName constant
	pg.file.Commentf("ProviderName is the Terraform provider name.")
	pg.file.Const().Id("ProviderName").Op("=").Lit(providerName)
	pg.file.Line()

	// NewProvider function
	pg.file.Comment("NewProvider creates a new provider configuration.")
	pg.file.Func().Id("NewProvider").Params().Op("*").Id("ProviderConfig").Block(
		jen.Return(jen.Op("&").Id("ProviderConfig").Values()),
	)
}

// File returns the generated jennifer file.
func (pg *ProviderGenerator) File() *jen.File {
	return pg.file
}
